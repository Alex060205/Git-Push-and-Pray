package com.example.vitala.pacing

import java.time.LocalDate

enum class Dimension {
    MINUTES,
    REPETITIONS,
    INTENSITY,
    RESISTANCE_KG,
    SESSIONS_PER_WEEK
}

/**
 * Use the same intensity scale throughout an exercise's prescription.
 * For example, intensityScale = "clinician-defined level 1–5".
 */
data class Dose(
    val values: Map<Dimension, Double>,
    val intensityScale: String? = null
) {
    init {
        require(values.isNotEmpty())
        require(values.values.all { it.isFinite() && it >= 0.0 })

        values[Dimension.SESSIONS_PER_WEEK]?.let {
            require(it > 0.0 && it <= 7.0 && it % 1.0 == 0.0)
        }

        values[Dimension.REPETITIONS]?.let {
            require(it % 1.0 == 0.0)
        }

        if (Dimension.INTENSITY in values) {
            require(!intensityScale.isNullOrBlank())
        }
    }

    fun change(dimension: Dimension, amount: Double): Dose {
        require(dimension in values)
        return copy(values = values + (dimension to amount))
    }
}

enum class Symptoms {
    FAMILIAR_WITHIN_RANGE,
    FAMILIAR_ABOVE_RANGE,
    NEW_OR_DIFFERENT
}

enum class Recovery {
    SAME_DAY,
    NEXT_DAY,
    LATER,
    STILL_ABOVE_USUAL,
    UNSURE
}

enum class IncompleteReason {
    DISCOMFORT,
    FATIGUE,
    PRACTICAL,
    OTHER
}

data class SessionReport(
    val id: String,
    val exerciseId: String,
    val date: LocalDate,
    val prescribed: Dose,
    val actual: Dose,
    val confirmedComplete: Boolean,
    val symptoms: Symptoms,
    val incompleteReason: IncompleteReason? = null
) {
    val completedAsPrescribed: Boolean
        get() = confirmedComplete && actual == prescribed

    init {
        require(completedAsPrescribed || incompleteReason != null) {
            "A shortened, skipped or unconfirmed session needs a reason."
        }
    }
}

data class DailyReport(
    val date: LocalDate,
    val pain: Int,
    val fatigue: Int,
    val interference: Int,

    // Compare changes with clinician-supplied usual/reference values.
    val referencePain: Int?,
    val referenceFatigue: Int?,
    val referenceInterference: Int?,

    // Required when evaluating a dose change or flare.
    val recovery: Recovery?,

    // Optional context selection plus optional explanatory note.
    val contextChanged: Boolean,
    val contextNote: String? = null,

    /**
     * Answers to clinician-defined review/urgent questions.
     * Missing key = unknown, not false.
     */
    val triggerAnswers: Map<String, Boolean> = emptyMap()
) {
    init {
        require(listOf(pain, fatigue, interference).all { it in 0..10 })
        require(
            listOfNotNull(
                referencePain,
                referenceFatigue,
                referenceInterference
            ).all { it in 0..10 }
        )
    }
}

data class PegReport(
    val date: LocalDate,
    val averagePain: Int,
    val enjoymentInterference: Int,
    val activityInterference: Int
) {
    init {
        require(
            listOf(
                averagePain,
                enjoymentInterference,
                activityInterference
            ).all { it in 0..10 }
        )
    }
}

data class PatientHistory(
    // Sessions must be in chronological order within each date.
    val sessions: List<SessionReport>,
    val days: List<DailyReport>,
    val peg: List<PegReport>
)

data class Progression(
    val dimension: Dimension,
    val increment: Double,
    val maximum: Double,
    val minimumDaysBetweenChanges: Int,
    val observationDays: Int,
    val requiredCompletedSessions: Int
) {
    init {
        require(increment.isFinite() && increment > 0.0)
        require(maximum.isFinite() && maximum >= 0.0)
        require(minimumDaysBetweenChanges >= 1)
        require(observationDays >= 1)
        require(requiredCompletedSessions >= 1)
    }
}

data class PrescriptionAction(
    val dose: Dose?,
    val instructions: String
)

data class IncompleteInstructions(
    val duringSession: String,
    val nextAttempt: PrescriptionAction
)

data class DoctorPrescription(
    val exerciseId: String,
    val activity: String,
    val technique: String,
    val currentDose: Dose,
    val effectiveFrom: LocalDate,
    val progression: Progression,

    /**
     * Conditions that must be satisfied before progressing.
     * Daily and session conditions apply across the observation window.
     */
    val acceptableDailyResponse: Condition,
    val acceptableSessionResponse: Condition,
    val acceptableWeeklyResponse: Condition? = null,

    /**
     * Conditions that trigger an action.
     * Conditions are supplied by your teammate, not generated by the engine.
     */
    val rollbackWhen: Condition,
    val reviewWhen: Condition,
    val urgentWhen: Condition,

    val fallback: PrescriptionAction,
    val reviewAction: PrescriptionAction,
    val urgentAction: PrescriptionAction,

    val incompleteInstructions:
    Map<IncompleteReason, IncompleteInstructions>
)

enum class Action {
    INCREASE,
    MAINTAIN,
    DECREASE,
    INCOMPLETE_SESSION,
    REVIEW,
    URGENT,
    NEEDS_INFORMATION,
    NEEDS_CONFIGURATION
}

data class Recommendation(
    val action: Action,
    val nextDose: Dose?,
    val reason: String,
    val instructions: String,
    val matchedRule: String,
    val evidence: Map<String, String> = emptyMap()
)